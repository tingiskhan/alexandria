"""Alembic's environment: runs the migrations on the connection `alexandria_core.migrate` hands it.

Alembic is configured in code (`alexandria_core.migrate.alembic_config`), not from an alembic.ini, so the
migrations work wherever the package is installed. Use `alexandria-db` rather than the `alembic` command.
"""

from typing import Literal

from alembic import context
from alembic.autogenerate.api import AutogenContext
from pgvector.sqlalchemy import Vector
from sqlalchemy import Connection

from alexandria_core.db import Base


def render_item(kind: str, item: object, autogen_context: AutogenContext) -> str | Literal[False]:
    """Write pgvector columns as `Vector(1024)` in autogenerated revisions, with the import they need."""
    if kind == "type" and isinstance(item, Vector):
        autogen_context.imports.add("from pgvector.sqlalchemy import Vector")
        return f"Vector({item.dim})"
    return False  # Alembic's default rendering


connection = context.config.attributes.get("connection")
if not isinstance(connection, Connection):
    raise RuntimeError("Run migrations with alexandria-db or alexandria_core.migrate, which pass a connection")

context.configure(connection=connection, target_metadata=Base.metadata, compare_type=True, render_item=render_item)
with context.begin_transaction():
    context.run_migrations()
